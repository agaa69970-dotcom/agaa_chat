class Prefs extends ChangeNotifier {
  static final Prefs i = Prefs._();
  Prefs._();

  SharedPreferences? _p;
  ThemeMode mode = ThemeMode.dark;
  int wall = 0;
  double fontScale = 1.0;
  bool alertSound = true;
  String fx = 'normal';

  Future<void> load() async {
    try {
      final p = await SharedPreferences.getInstance();
      _p = p;
      final m = p.getInt('pm') ?? 2;
      mode = m == 0 ? ThemeMode.system : (m == 1 ? ThemeMode.light : ThemeMode.dark);
      wall = p.getInt('pw') ?? 0;
      fontScale = p.getDouble('pf') ?? 1.0;
      alertSound = p.getBool('pa') ?? true;
      fx = p.getString('px') ?? 'normal';
    } catch (_) {}
  }

  Future<void> _save() async {
    final p = _p;
    if (p == null) return;
    try {
      await p.setInt('pm', mode == ThemeMode.system ? 0 : (mode == ThemeMode.light ? 1 : 2));
      await p.setInt('pw', wall);
      await p.setDouble('pf', fontScale);
      await p.setBool('pa', alertSound);
      await p.setString('px', fx);
    } catch (_) {}
  }

  void setMode(ThemeMode m) {
    mode = m;
    _save();
    notifyListeners();
  }

  void setWall(int w) {
    wall = w;
    _save();
    notifyListeners();
  }

  void setFont(double f) {
    fontScale = f;
    _save();
    notifyListeners();
  }

  void setSound(bool v) {
    alertSound = v;
    _save();
    notifyListeners();
  }

  void setFx(String id) {
    fx = id;
    _save();
  }
}
