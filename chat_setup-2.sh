/// مشغّل واحد مشترك: يشغّل الرسالة بتأثير الصوت المختار.
class VPlayer {
  static final VPlayer i = VPlayer._();
  VPlayer._();

  final AudioPlayer _p = AudioPlayer();
  final ValueNotifier<String?> current = ValueNotifier<String?>(null);
  final ValueNotifier<bool> loading = ValueNotifier<bool>(false);
  final ValueNotifier<double> rate = ValueNotifier<double>(1.0);

  void cycleRate() {
    rate.value = rate.value >= 2.0 ? 1.0 : (rate.value >= 1.5 ? 2.0 : 1.5);
  }

  Future<void> stop() async {
    current.value = null;
    try {
      await _p.stop();
    } catch (_) {}
  }

  Future<void> playPath(String key, String path, Fx fx) async {
    if (current.value == key) {
      await stop();
      return;
    }
    await stop();
    current.value = key;
    try {
      await _p.setFilePath(path);
      await _p.setPitch(fx.pitch);
      await _p.setSpeed(fx.speed * rate.value);
      await _p.play();
    } catch (_) {}
    if (current.value == key) current.value = null;
  }

  Future<void> playMsg(Msg m) async {
    final key = 'm${m.id}';
    if (current.value == key) {
      await stop();
      return;
    }
    loading.value = true;
    String path;
    try {
      path = await Api.voiceFile(m);
    } finally {
      loading.value = false;
    }
    await playPath(key, path, fxById(m.effect));
  }
}
